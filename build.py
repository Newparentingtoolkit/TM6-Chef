"""Builds app/prompt.js from gem-prompt.md (+ the app-only addendum) and draws the app icons.
Run after editing gem-prompt.md:  python build.py
"""
import json, struct, zlib, pathlib

root = pathlib.Path(__file__).parent
gem = (root / "gem-prompt.md").read_text(encoding="utf-8").strip()

addendum = """APP MODE
You are running inside a phone app that has its own Cook mode (a step-by-step screen with timers), a recipe library and a shopping list. Therefore:
- Do not walk the user through steps in chat unless they explicitly ask; tell them to tap "Start cooking" on the recipe card instead.
- When you give a COMPLETE recipe (new, converted or adapted), write only a one or two sentence intro, then end the message with ONE fenced code block labelled recipe that contains valid JSON (no comments, no trailing commas). The app draws the recipe from it. Never repeat the ingredients or steps in prose.
- JSON shape: __SCHEMA__
- "tm" holds the Thermomix settings of that step (time like "5 sec" or "10 min", temp like "100" or "Varoma", speed like "1" or "Turbo"); use null when the step has no machine settings. "timer_min" is only for waiting outside the machine (resting, oven, chilling), otherwise null.
- Write all text inside the JSON in the user's language.
- For every other reply (questions, tips, troubleshooting, clarifications) answer in short plain text with no JSON."""

schema = '{"title":"","description":"","servings":4,"prep_min":10,"cook_min":25,"total_min":35,"difficulty":"easy|medium|advanced","equipment":["butterfly whisk"],"ingredients":[{"group":"","amount":"200 g","name":"tomatoes"}],"steps":[{"text":"Place onion into the mixing bowl and chop.","tm":{"time":"5 sec","temp":"","speed":"5","reverse":false,"mode":""},"timer_min":null}],"tips":[""]}'
addendum = addendum.replace("__SCHEMA__", schema)

js = "// Generated by build.py - do not edit by hand.\nconst GEM_PROMPT = %s;\nconst APP_ADDENDUM = %s;\nconst RECIPE_SCHEMA = %s;\n" % (
    json.dumps(gem, ensure_ascii=False), json.dumps(addendum, ensure_ascii=False), json.dumps(schema))
(root / "app" / "prompt.js").write_text(js, encoding="utf-8")


def png(size, path):
    """Green rounded square with a white pot silhouette, plain Python (no libraries)."""
    green, white = (31, 111, 84), (255, 255, 255)
    rows = []
    r = size * 0.22
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            # rounded square mask
            dx = max(r - x, 0, x - (size - 1 - r)); dy = max(r - y, 0, y - (size - 1 - r))
            if dx * dx + dy * dy > r * r:
                row += bytes((0, 0, 0, 0)); continue
            u, v = x / size, y / size
            pot = 0.28 <= u <= 0.72 and 0.42 <= v <= 0.72 and ((u - 0.5) ** 2 / 0.05 + 0 < 9)  # body
            lid = 0.24 <= u <= 0.76 and 0.36 <= v <= 0.42
            knob = (u - 0.5) ** 2 + (v - 0.31) ** 2 < 0.0025
            hand = (0.20 <= u <= 0.28 or 0.72 <= u <= 0.80) and 0.48 <= v <= 0.54
            steam = any(abs(u - cx - 0.02 * __import__("math").sin(v * 40)) < 0.012 and 0.14 <= v <= 0.28 for cx in (0.40, 0.60)) and False
            col = white if (pot or lid or knob or hand) else green
            row += bytes((*col, 255))
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    path.write_bytes(data)


png(192, root / "app" / "icon-192.png")
png(512, root / "app" / "icon-512.png")
print("built prompt.js (%d chars) and icons" % len(js))
